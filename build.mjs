import {readFile,writeFile} from 'node:fs/promises';
const get=name=>readFile(new URL(name,import.meta.url),'utf8');
const [template,ui,css]=await Promise.all(['client-source.js','garden-ui.js','garden.css'].map(get));
if(!ui.includes('export const UI_STRINGS =')||!ui.includes('export function createGarden(React)'))throw Error('Garden UI export contract changed');
const localUI=ui.replace('export const UI_STRINGS =','const UI_STRINGS =').replace('export function createGarden(React)','function createGarden(React)');
if(/^\s*(?:import\s|export\s)/m.test(localUI))throw Error('Garden UI must remain self-contained for desktop bundling');
const output='// Generated by build.mjs; edit client-source.js, garden-ui.js and garden.css.\n'+template.replace('/* INLINE_GARDEN_UI */',()=>localUI).replace('/* INLINE_GARDEN_CSS */',()=>JSON.stringify(css));
if(output.includes('/* INLINE_GARDEN_'))throw Error('Unresolved build marker');
await writeFile(new URL('client.js',import.meta.url),output);
const manifest=JSON.parse(await get('package.json'));
const host=await get('index.js');
await writeFile(new URL(manifest.exports['.'],import.meta.url),'// Generated Host artifact. Source: index.js\n'+host);
await writeFile(new URL(manifest.exports['./client'],import.meta.url),output);
console.log(`Built version ${manifest.version}: self-contained desktop Client (${Buffer.byteLength(output)} bytes) and versioned Host artifact`);
